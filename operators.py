#Arithmetic operators
no1=(int(input("value1:")))
no2=(int(input("value2:")))
print("add:",no1+no2)
print("substraction:",no1-no2)
print("division:",no1/no2)
print("multiplication:",no1*no2)
print("modulous:",no1%no2)
#relational operators
print(" greater than:",no1>no2)
print("less than:",no1<no2)
print("greater than or equal to:",no1>=no2)
print("less than or equal to:",no1<=no2)
print("not:",no1!=no2)
#logical operator
print(no1>15 and no2<15)
print(no1>15 or no2<15)


